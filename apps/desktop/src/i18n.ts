const dicts: Record<Lang, Record<string, string>> = { es, en };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? dicts.es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export const I18nContext = createContext<{ lang: Lang; t: (k: string, vars?: Record<string, string | number>) => string }>({
  lang: "es",
  t: (k, vars) => translate("es", k, vars),
});

export const useT = () => useContext(I18nContext);

export function formatDate(secs: number | null | undefined, lang: Lang, never: string): string {
  if (!secs) return never;
  return new Date(secs * 1000).toLocaleString(lang === "es" ? "es-HN" : "en-US", { dateStyle: "medium", timeStyle: "short" });
}
